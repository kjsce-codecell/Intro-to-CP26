// Assignment Operators
#include <bits/stdc++.h>
using namespace std;

int main()
{
    int a = 10, b = 20;

    cout << "Initial a = " << a << "\n";
    cout << "a+=2 :" << (a+=2) << "\n";
    cout << "Updated a = " << a << "\n";
    cout << "a-=2 :" << (a-=2) << "\n";
    cout << "Updated a = " << a << "\n";
    cout << "a*=2 :" << (a*=2) << "\n";
    cout << "Updated a = " << a << "\n";
    cout << "a/=2 :" << (a/=2) << "\n";
    cout << "Updated a = " << a << "\n";
    cout << "a%=2 :" << (a%=2) << "\n";
    cout << "Updated a = " << a << "\n";
}