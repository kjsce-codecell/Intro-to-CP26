//Relational Operators
#include <bits/stdc++.h>
using namespace std;

int main()
{
    int a = 10, b = 20;

    cout << (a == b) << "\n";  // equal to
    cout << (a != b) << "\n";  // not equal to
    cout << (a > b)  << "\n";  // greater than
    cout << (a < b)  << "\n";  // less than
    cout << (a >= b) << "\n";  // greater than or equal to
    cout << (a <= b) << "\n";  // less than or equal to
}