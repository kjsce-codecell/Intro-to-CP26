// Using auto keyword

#include <bits/stdc++.h>
using namespace std;

int main(){
    auto a = 42;          
    

    auto b = 3.14;       
    
    auto c = "Hello";       


    cout << "Number: " << a << "\n";
    cout << "Decimal: " << b << "\n";
    cout << "Text: " << c << "\n";
    
    return 0;
}
